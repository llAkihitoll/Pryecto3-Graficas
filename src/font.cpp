static const Glyph* findGlyph(char c) {
    c = (char)std::toupper((unsigned char)c);
    for (const Glyph& g : GLYPHS) {
        if (g.c == c) return &g;
    }
    return nullptr; // espacio o caracter sin dibujo
}

static void drawGlyphs(Framebuffer& fb, int x, int y, const std::string& text, uint32_t argb, int scale) {
    for (char ch : text) {
        const Glyph* g = findGlyph(ch);
        if (g) {
            for (int row = 0; row < 7; ++row)
                for (int col = 0; col < 5; ++col) {
                    if (g->rows[row][col] != '#') continue;
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx) {
                            int px = x + col * scale + sx, py = y + row * scale + sy;
                            if (px >= 0 && py >= 0 && px < fb.width() && py < fb.height()) fb.setPixel(px, py, argb);
                        }
                }
        }
        x += GLYPH_WIDTH * scale;
    }
}

void drawText(Framebuffer& fb, int x, int y, const std::string& text, uint32_t argb, int scale) {
    drawGlyphs(fb, x + scale, y + scale, text, 0xFF000000u, scale); // sombra
    drawGlyphs(fb, x, y, text, argb, scale);
}

int textWidth(const std::string& text, int scale) { return (int)text.size() * GLYPH_WIDTH * scale; }
